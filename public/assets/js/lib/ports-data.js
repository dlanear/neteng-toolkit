export function findByPort(port) {
  const p = Number(port);
  return PORTS.filter((entry) => entry.port === p);
}

export function findByService(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PORTS.filter((entry) => entry.service.toLowerCase().includes(q));
}
